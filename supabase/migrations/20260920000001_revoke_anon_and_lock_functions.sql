-- Withdraw anonymous access, and stop every database function being callable over the API.
--
-- Found 2026-09-20 while revoking the view grants: 44 tables returned data to a caller
-- with no session at all, including chat_messages, push_subscriptions and notifications.
-- Cause: 243 of 448 row-security policies name the `public` role (which includes `anon`),
-- and the anonymous role holds table grants by platform default. Rather than rewrite the
-- policies, withdraw the grants: an anonymous caller is then refused before any policy is
-- consulted. Nothing in the app reads as `anon` except one profile lookup on the landing
-- page that already returns nothing and tolerates it.
--
-- Functions: all of them granted EXECUTE to PUBLIC, so 178 were callable as RPC, 52 of
-- them running with owner rights. Revoked wholesale, then granted back to `authenticated`
-- for the nine used inside row-security policies and the five called from the browser.
-- Extension-owned functions are left alone. service_role holds its own grants throughout.
--
-- Applied to production: 2026-09-20.

